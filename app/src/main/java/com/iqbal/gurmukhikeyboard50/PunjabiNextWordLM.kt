    private fun loadPredictionsFromAssets(context: Context) {
        try {
            val folders = listOf(
                "gurbani/guru_granth_sahib/japji_sahib",
                "gurbani/guru_granth_sahib/sri_raag",
                "gurbani/guru_granth_sahib/raag_asa"
            )

            for (folder in folders) {
                val filePath = "$folder/content.txt"
                try {
                    context.assets.open(filePath).use { inputStream ->
                        BufferedReader(InputStreamReader(inputStream)).use { reader ->
                            var line: String?
                            while (reader.readLine().also { line = it } != null) {
                                processLine(line!!)
                            }
                        }
                    }
                } catch (e: Exception) { }
            }
        } catch (e: Exception) { }
    }

    private fun processLine(line: String) {
        val words = line.trim().split(Regex("\\s+"))
        if (words.size < 2) return

        for (i in 0 until words.size - 1) {
            val currentWord = words[i]
            val nextWord = words[i + 1]

            if (currentWord.length < 2 || nextWord.length < 2) continue

            val currentPredictions = nextWordMap[currentWord]?.toMutableList() ?: mutableListOf()
            if (!currentPredictions.contains(nextWord)) {
                currentPredictions.add(nextWord)
                nextWordMap[currentWord] = currentPredictions.take(30)
            }
        }
    }

    fun predict(input: String): List<String> {
        if (input.isEmpty()) return emptyList()
        
        val lastWord = input.trim().split(Regex("\\s+")).last()
        
        val predictions = nextWordMap[lastWord]?.toMutableList() ?: mutableListOf()
        
        // Character-based fallback if no word match
        if (predictions.isEmpty() && lastWord.length == 1) {
            nextWordMap[lastWord]?.let { charPredictions ->
                predictions.addAll(charPredictions)
            }
        }
        
        return predictions.distinct().take(20) // Show up to 20 suggestions as requested
    }
